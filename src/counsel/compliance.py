"""The OWASP map: compliance/owasp.yaml rendered to docs/compliance.md.

Every row names its evidence, a test (`tests/x.py::test_name`) or a file. Rendering
fails if any of it does not exist, so the table cannot cite a test that was renamed
or deleted. CI runs the tests themselves, so a published row's evidence passed.
"""

from __future__ import annotations

import ast
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "compliance" / "owasp.yaml"
OUTPUT = ROOT / "docs" / "compliance.md"
REPO = "https://github.com/shanurwan/counsel/blob/main"
COVERAGE = {"full": "Full", "partial": "Partial", "n/a": "Not applicable"}


class ComplianceError(Exception):
    def __init__(self, problems: list[str]):
        super().__init__("\n".join(problems))
        self.problems = problems


def _tests_in(path: Path) -> set[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    return {n.name for n in tree.body if isinstance(n, ast.FunctionDef) and n.name.startswith("test_")}


def check(doc: dict, root: Path = ROOT) -> list[str]:
    problems = []
    frameworks = doc.get("frameworks") or {}
    seen = set()
    for risk in doc.get("risks") or []:
        rid = risk.get("id", "?")
        if rid in seen:
            problems.append(f"{rid}: listed twice")
        seen.add(rid)
        if risk.get("framework") not in frameworks:
            problems.append(f"{rid}: unknown framework {risk.get('framework')!r}")
        if risk.get("coverage") not in COVERAGE:
            problems.append(f"{rid}: coverage must be one of {', '.join(COVERAGE)}")
        for key in ("name", "how", "remains"):
            if not str(risk.get(key) or "").strip():
                problems.append(f"{rid}: missing {key}")
        if not risk.get("evidence"):
            problems.append(f"{rid}: no evidence")
        for item in risk.get("evidence") or []:
            file, _, test = str(item).partition("::")
            path = root / file
            if not path.exists():
                problems.append(f"{rid}: {file} does not exist")
            elif test and test not in _tests_in(path):
                problems.append(f"{rid}: {file} has no test {test}")
    missing = [f"ASI{i:02d}" for i in range(1, 11) if f"ASI{i:02d}" not in seen]
    if missing:
        problems.append(f"every OWASP Agentic risk needs a row; missing {', '.join(missing)}")
    return problems


def _evidence(item: str) -> str:
    file, _, test = item.partition("::")
    label = f"`{test}`" if test else f"`{file}`"
    return f"[{label}]({REPO}/{file})"


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def render(doc: dict) -> str:
    risks = doc["risks"]
    counts = {c: sum(r["coverage"] == c for r in risks) for c in COVERAGE}
    out = [
        "# OWASP coverage",
        "",
        "<!-- GENERATED by `counsel compliance` from compliance/owasp.yaml. Do not edit. -->",
        "",
        f"What Counsel does about each risk, the tests that show it, and what remains. "
        f"Reviewed {doc['reviewed']} by {doc['owner']}. CI regenerates this page and fails if a row "
        f"cites a test or file that does not exist, and runs every cited test.",
        "",
        f"**{counts['full']} full, {counts['partial']} partial, {counts['n/a']} not applicable** "
        f"across {len(risks)} risks. Partial means the gap is named in the last column, not hidden.",
    ]
    for key, framework in doc["frameworks"].items():
        rows = [r for r in risks if r["framework"] == key]
        if not rows:
            continue
        out += ["", f"## [{framework['name']}]({framework['url']})", "",
                "| Risk | Coverage | How Counsel handles it | Evidence | What remains |",
                "|---|---|---|---|---|"]
        for r in rows:
            out.append(f"| **{r['id']}** {_cell(r['name'])} | {COVERAGE[r['coverage']]} | {_cell(r['how'])} | "
                       f"{'<br>'.join(_evidence(str(e)) for e in r['evidence'])} | {_cell(r['remains'])} |")
    return "\n".join(out) + "\n"


def build(source: Path = SOURCE) -> str:
    doc = yaml.safe_load(source.read_text(encoding="utf-8"))
    problems = check(doc)
    if problems:
        raise ComplianceError(problems)
    return render(doc)
