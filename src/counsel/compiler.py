"""Compile the registry into roles and grants.

Every statement an agent's role can ever receive is written out below. There is
no template that grants INSERT or UPDATE on work.tasks, so there is nothing to
misconfigure. The output is idempotent: each run revokes everything from every
agent role and grants back exactly what the registry says.
"""

from __future__ import annotations

from .registry import Agent

RUNTIME_ROLE = "counsel_runtime"
GROUP_ROLE = "counsel_agents"
ORCHESTRATOR_ROLE = "counsel_orchestrator"

CAPABILITY_SQL: dict[str, list[str]] = {
    "read_handbook": [
        "grant usage on schema kb to {role};",
        "grant select on kb.documents to {role};",
    ],
    "write_answers": [
        "grant insert (id, run_id, question, body) on counsel.answers to {role};",
    ],
    "read_tasks": [
        "grant usage on schema work to {role};",
        "grant select on work.teams, work.people, work.tasks to {role};",
    ],
    "read_updates": [
        "grant usage on schema work to {role};",
        "grant select on work.task_updates to {role};",
    ],
    "read_tickets": [
        "grant usage on schema support to {role};",
        "grant select (id, customer_id, subject, body, created_at) on support.tickets to {role};",
        "grant select (id, ticket_id, author, body, created_at) on support.ticket_messages to {role};",
    ],
    "write_drafts": [
        "grant insert (id, run_id, kind, body) on counsel.drafts to {role};",
    ],
    "draft_support_replies": [
        "grant insert (id, run_id, kind, body) on counsel.drafts to {role};",
    ],
    "carry_updates": [
        "grant usage on schema work to {role};",
        # Row-level security limits this to the one standup the run was started for.
        "grant select (id, person_id, body, created_at) on work.standups to {role};",
        "grant insert (task_id, body, consent_id) on work.task_updates to {role};",
    ],
    "send_messages": [
        "grant insert (run_id, recipient_id, body) on counsel.outbound_messages to {role};",
    ],
}

# The compiler's job is to write SQL text, so it formats strings. Every value
# it interpolates is either a constant here or an agent name/owner that
# registry.validate_entry has already matched against a strict pattern, and
# descriptions only ever land inside single-line comments.
HEADER = """\
-- GENERATED by `counsel compile` from agents/*.yaml. Do not edit.
-- CI fails if this file differs from a fresh compile.
-- `counsel migrate` applies it in one transaction.

-- Shared by every agent: write its own audit entries, nothing else.
grant usage on schema counsel to {group};
grant insert (run_id, action, target, decision, detail) on counsel.audit_log to {group};

-- The runtime logs in, holds no privileges itself (NOINHERIT), and must
-- SET ROLE to one agent per step. Its password is set at deploy time.
do $$
begin
  if not exists (select from pg_roles where rolname = '{runtime}') then
    create role {runtime} login noinherit;
  end if;
end $$;
alter role {runtime} noinherit nocreatedb nocreaterole nobypassrls;

-- Bookkeeping (jobs, runs, journal) happens as the orchestrator, created in
-- 0003_runtime.sql and audited like an agent.
grant {orchestrator} to {runtime};
"""

AGENT_BLOCK = """
-- {name} ({tier}) owner: {owner}
-- {description}
do $$
begin
  if not exists (select from pg_roles where rolname = '{role}') then
    create role {role} nologin;
  end if;
end $$;
alter role {role} nologin nocreatedb nocreaterole nobypassrls;
grant {group} to {role};
grant {role} to {runtime};
revoke all on all tables in schema work, kb, counsel, support from {role};
revoke all on schema work, kb, counsel, support from {role};
{grants}
"""


def grants_for(agent: Agent) -> list[str]:
    seen: list[str] = []
    for cap in agent.capabilities:
        for stmt in CAPABILITY_SQL[cap]:
            line = stmt.format(role=agent.role)
            if line not in seen:
                seen.append(line)
    return seen


def _sql_number(value: float | int | None) -> str:
    return "null" if value is None else repr(value)


SETTINGS_BLOCK = """
-- Per-agent settings for the value ledger and budgets (0008_ledger.sql).
insert into counsel.agent_settings (agent, owner, minutes_per_output, budget_usd) values
  {rows}
on conflict (agent) do update set owner = excluded.owner,
  minutes_per_output = excluded.minutes_per_output, budget_usd = excluded.budget_usd;
delete from counsel.agent_settings where agent not in ({names});
"""


def settings_sql(agents: list[Agent]) -> str:
    """What the value ledger and budgets read: one row per registered agent."""
    ordered = sorted(agents, key=lambda a: a.name)
    rows = ",\n  ".join(
        "('{}', '{}', {}, {})".format(a.name, a.owner, _sql_number(a.minutes_per_output), _sql_number(a.budget_usd))
        for a in ordered)
    return SETTINGS_BLOCK.format(rows=rows, names=", ".join(f"'{a.name}'" for a in ordered))


def compile_sql(agents: list[Agent]) -> str:
    out = [HEADER.format(group=GROUP_ROLE, runtime=RUNTIME_ROLE, orchestrator=ORCHESTRATOR_ROLE)]
    for agent in sorted(agents, key=lambda a: a.name):
        out.append(AGENT_BLOCK.format(
            name=agent.name,
            tier=agent.tier,
            owner=agent.owner,
            description=agent.description,
            role=agent.role,
            group=GROUP_ROLE,
            runtime=RUNTIME_ROLE,
            grants="\n".join(grants_for(agent)),
        ))
    out.append(settings_sql(agents))
    return "".join(out)
